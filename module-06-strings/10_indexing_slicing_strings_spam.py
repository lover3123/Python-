spam = 'Hello world!'
spam[0]
# OUT: 'H'
spam[4]
# OUT: 'o'
spam[-1]
# OUT: '!'
spam[0:5]
# OUT: 'Hello'
spam[:5]
# OUT: 'Hello'
spam[6:]
# OUT: 'world!'
